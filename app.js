/* --------------------------------------------------------------------------
   9. Interactions & Event Handlers
   -------------------------------------------------------------------------- */
function bindInteractions() {
  // Mobile navigation drawer toggle
  const mobileBtn = document.getElementById('mobile-menu-btn');
  const mobileMenu = document.getElementById('mobile-menu');
  if (mobileBtn && mobileMenu) {
    mobileBtn.addEventListener('click', () => {
      mobileMenu.classList.toggle('hidden');
    });

    mobileMenu.querySelectorAll('a').forEach(link => {
      link.addEventListener('click', () => {
        mobileMenu.classList.add('hidden');
      });
    });
  }

  // Publication filter tabs
  const pubTabs = document.querySelectorAll('.pub-tab');
  pubTabs.forEach(tab => {
    tab.addEventListener('click', () => {
      pubTabs.forEach(t => t.classList.remove('active'));
      tab.classList.add('active');
      currentPubFilter = tab.getAttribute('data-pub') || 'all';
      renderPublications(PORTFOLIO_DATA.publications, currentPubFilter, currentPubSearch);
    });
  });

  // Publication search bar
  const searchInput = document.getElementById('pub-search-input');
  if (searchInput) {
    searchInput.addEventListener('input', (e) => {
      currentPubSearch = e.target.value;
      renderPublications(PORTFOLIO_DATA.publications, currentPubFilter, currentPubSearch);
    });
  }

  // Neural visualizer architecture switcher buttons
  const archButtons = document.querySelectorAll('.arch-btn');
  archButtons.forEach(btn => {
    btn.addEventListener('click', () => {
      archButtons.forEach(b => b.classList.remove('active'));
      btn.classList.add('active');
      const arch = btn.getAttribute('data-arch') || 'SHAP';
      initNeuralVisualizer(arch);
    });
  });

  // Carousel previous / next buttons
  const prevBtn = document.getElementById('prev-proj');
  const nextBtn = document.getElementById('next-proj');
  if (prevBtn) {
    prevBtn.addEventListener('click', () => {
      renderProjectSpotlight(currentProjectIndex - 1);
    });
  }
  if (nextBtn) {
    nextBtn.addEventListener('click', () => {
      renderProjectSpotlight(currentProjectIndex + 1);
    });
  }

  // Carousel dot indicators delegation
  const dotsContainer = document.getElementById('carousel-dots');
  if (dotsContainer) {
    dotsContainer.addEventListener('click', (e) => {
      const btn = e.target.closest('button[data-slide]');
      if (btn) {
        const slideIdx = parseInt(btn.getAttribute('data-slide'), 10);
        renderProjectSpotlight(slideIdx);
      }
    });
  }

  // Keyboard navigation for project carousel
  window.addEventListener('keydown', (e) => {
    if (e.target.tagName === 'INPUT' || e.target.tagName === 'TEXTAREA') return;
    if (e.key === 'ArrowLeft') {
      renderProjectSpotlight(currentProjectIndex - 1);
    } else if (e.key === 'ArrowRight') {
      renderProjectSpotlight(currentProjectIndex + 1);
    }
  });

  // Toggle "View All 8 Grid" vs "Spotlight View"
  const toggleBtn = document.getElementById('toggle-all-projects');
  const spotlightSection = document.getElementById('project-spotlight');
  const carouselControls = document.getElementById('carousel-controls');
  const allGrid = document.getElementById('all-projects-grid');
  const toggleLabel = document.getElementById('toggle-projects-label');

  if (toggleBtn && allGrid && spotlightSection && carouselControls) {
    toggleBtn.addEventListener('click', () => {
      isAllProjectsExpanded = !isAllProjectsExpanded;
      if (isAllProjectsExpanded) {
        allGrid.classList.remove('hidden');
        allGrid.classList.add('grid');
        spotlightSection.classList.add('hidden');
        carouselControls.classList.add('hidden');
        if (toggleLabel) toggleLabel.textContent = 'View Spotlight Carousel';
      } else {
        allGrid.classList.add('hidden');
        allGrid.classList.remove('grid');
        spotlightSection.classList.remove('hidden');
        carouselControls.classList.remove('hidden');
        if (toggleLabel) toggleLabel.textContent = 'View All 8 Grid';
      }
    });
  }

  // BibTeX Citation Modal Handling
  document.addEventListener('click', (e) => {
    const citeBtn = e.target.closest('.cite-btn');
    if (citeBtn) {
      const pubId = citeBtn.getAttribute('data-cite-id');
      const pub = PORTFOLIO_DATA.publications.find(p => p.id === pubId);
      if (pub && pub.bibtex) {
        openCiteModal(pub.bibtex);
      }
    }
  });

  const closeCiteBtn = document.getElementById('close-cite-modal');
  const citeModal = document.getElementById('cite-modal');
  if (closeCiteBtn && citeModal) {
    closeCiteBtn.addEventListener('click', () => {
      citeModal.classList.add('hidden');
      citeModal.classList.remove('flex');
    });

    citeModal.addEventListener('click', (e) => {
      if (e.target === citeModal) {
        citeModal.classList.add('hidden');
        citeModal.classList.remove('flex');
      }
    });
  }

  const copyCiteBtn = document.getElementById('copy-cite-btn');
  if (copyCiteBtn) {
    copyCiteBtn.addEventListener('click', () => {
      const content = document.getElementById('cite-content');
      if (content) {
        navigator.clipboard.writeText(content.textContent).then(() => {
          showToast('BibTeX citation copied to clipboard!');
          copyCiteBtn.innerHTML = '<i class="fa-solid fa-check"></i> Copied!';
          setTimeout(() => {
            copyCiteBtn.innerHTML = '<i class="fa-regular fa-copy"></i> Copy BibTeX';
          }, 2000);
        }).catch(() => {
          showToast('Could not copy automatically. Please copy manually.');
        });
      }
    });
  }

  // Copy email button
  const copyEmailBtns = document.querySelectorAll('.copy-email-btn');
  copyEmailBtns.forEach(btn => {
    btn.addEventListener('click', () => {
      navigator.clipboard.writeText('faizabintezaman@gmail.com').then(() => {
        showToast('Email address copied to clipboard!');
      });
    });
  });
}

function openCiteModal(bibtex) {
  const modal = document.getElementById('cite-modal');
  const content = document.getElementById('cite-content');
  if (!modal || !content) return;
  content.textContent = bibtex;
  modal.classList.remove('hidden');
  modal.classList.add('flex');
}

/* --------------------------------------------------------------------------
   10. Toast Notification System
   -------------------------------------------------------------------------- */
function showToast(message) {
  let toast = document.getElementById('portfolio-toast');
  if (!toast) {
    toast = document.createElement('div');
    toast.id = 'portfolio-toast';
    toast.className = 'fixed bottom-6 right-6 z-50 px-4 py-3 rounded-xl bg-[#253B74] border border-[#536DA8] text-[#E8EAF7] text-xs font-mono font-semibold shadow-2xl flex items-center gap-2 transform translate-y-16 opacity-0 transition-all duration-300';
    document.body.appendChild(toast);
  }

  toast.innerHTML = `<i class="fa-solid fa-circle-check text-emerald-400"></i> <span>${message}</span>`;
  toast.classList.remove('translate-y-16', 'opacity-0');
  toast.classList.add('translate-y-0', 'opacity-100');

  setTimeout(() => {
    toast.classList.remove('translate-y-0', 'opacity-100');
    toast.classList.add('translate-y-16', 'opacity-0');
  }, 2800);
}
