/* --------------------------------------------------------------------------
   1. Typewriter Animation
   -------------------------------------------------------------------------- */
function initTypewriter(phrases) {
  const el = document.getElementById('typewriter-text');
  if (!el || !phrases || !phrases.length) return;
  let pIdx = 0;
  let charIdx = 0;
  let deleting = false;

  function tick() {
    const current = phrases[pIdx];
    if (!deleting) {
      charIdx++;
      el.textContent = current.slice(0, charIdx);
      if (charIdx === current.length) {
        deleting = true;
        setTimeout(tick, 2200);
        return;
      }
      setTimeout(tick, 42);
    } else {
      charIdx--;
      el.textContent = current.slice(0, charIdx);
      if (charIdx === 0) {
        deleting = false;
        pIdx = (pIdx + 1) % phrases.length;
        setTimeout(tick, 350);
        return;
      }
      setTimeout(tick, 24);
    }
  }
  tick();
}

/* --------------------------------------------------------------------------
   2. Interactive SVG Computational Neural Visualizer
   -------------------------------------------------------------------------- */
function initNeuralVisualizer(mode) {
  const svg = document.getElementById('neural-svg');
  const label = document.getElementById('viz-mode-label');
  const desc = document.getElementById('viz-mode-desc');
  if (!svg) return;

  const architectures = {
    SHAP: {
      title: 'TreeSHAP Clinical Attribution Graph',
      desc: 'Additive feature attribution for non-linear tree ensembles (LightGBM/XGBoost)',
      layerLabels: ['Clinical Inputs', 'Tree Nodes', 'Interactions', 'SHAP Values'],
      layers: [4, 6, 6, 3],
      colors: ['#38BDF8', '#818CF8', '#C084FC', '#34D399']
    },
    Attn: {
      title: 'MentalBERT++ Multi-Head Attention',
      desc: 'Dual-representation Transformer with custom attention pooling for NLP triage',
      layerLabels: ['Token Embeddings', 'Q/K/V Projections', 'Cross-Attention', 'Risk Logits'],
      layers: [5, 5, 5, 4],
      colors: ['#60A5FA', '#A78BFA', '#F472B6', '#FBBF24']
    },
    CNN: {
      title: 'Histopathology ConvNet Pipeline',
      desc: 'Multi-scale spatial feature extraction across stained pulmonary WSI patches',
      layerLabels: ['WSI Patch', 'Conv + BatchNorm', 'Dense Bottleneck', 'Malignancy Class'],
      layers: [6, 5, 4, 2],
      colors: ['#2DD4BF', '#38BDF8', '#818CF8', '#F59E0B']
    }
  };

  const cfg = architectures[mode] || architectures.SHAP;
  if (label) label.textContent = cfg.title;
  if (desc) desc.textContent = cfg.desc;

  const width = 360;
  const height = 210;
  const xPositions = [38, 128, 222, 318];
  const nodes = [];

  cfg.layers.forEach((count, lIdx) => {
    const layerNodes = [];
    const spacing = height / (count + 1);
    for (let i = 0; i < count; i++) {
      layerNodes.push({
        x: xPositions[lIdx],
        y: Math.round(spacing * (i + 1)),
        color: cfg.colors[lIdx],
        label: `L${lIdx + 1}-N${i + 1}`
      });
    }
    nodes.push(layerNodes);
  });

  let edgesHtml = '';
  for (let l = 0; l < nodes.length - 1; l++) {
    nodes[l].forEach((src, sIdx) => {
      nodes[l + 1].forEach((dst, dIdx) => {
        // Selective dense connectivity with animated dash pulse
        if ((sIdx + dIdx) % 2 === 0 || l === nodes.length - 2 || (sIdx === 0 && dIdx === 0)) {
          const delay = ((sIdx * 0.2 + dIdx * 0.15 + l * 0.4) % 2.5).toFixed(2);
          edgesHtml += `
            <line x1="${src.x}" y1="${src.y}" x2="${dst.x}" y2="${dst.y}"
                  stroke="${src.color}" stroke-width="1.1" stroke-opacity="0.32"
                  class="neural-edge" style="animation-delay: -${delay}s;" />
          `;
        }
      });
    });
  }

  let nodesHtml = '';
  nodes.forEach((layer, lIdx) => {
    layer.forEach((n) => {
      nodesHtml += `
        <g class="neural-node cursor-pointer group" data-tooltip="${n.label}">
          <circle cx="${n.x}" cy="${n.y}" r="8" fill="${n.color}" fill-opacity="0.16" stroke="${n.color}" stroke-width="1.5" class="transition-all hover:scale-125" />
          <circle cx="${n.x}" cy="${n.y}" r="3" fill="${n.color}" />
        </g>
      `;
    });
  });

  // Layer column captions at bottom
  let labelsHtml = '';
  xPositions.forEach((x, idx) => {
    const labelText = cfg.layerLabels[idx] || `L${idx + 1}`;
    labelsHtml += `
      <text x="${x}" y="206" fill="#64748B" font-size="8.5" font-family="'JetBrains Mono', monospace" text-anchor="middle" font-weight="600">${labelText}</text>
    `;
  });

  svg.innerHTML = edgesHtml + nodesHtml + labelsHtml;
}

